// Generates PLACEHOLDER S-parameters for the homepage 3D Smith chart.
//
// This is NOT EM-simulated data. It is a textbook pi model of a CPW series
// gap (series Cs, shunt Cp to ground on each side) with a length of lossy
// CPW line on each side to move the reference planes. Replace
// public/smith/cpw-gap.s2p with the real export from the CPW
// discontinuity project when it exists.
//
// Run: node scripts/gen-cpw-placeholder.mjs

import { mkdirSync, writeFileSync } from 'node:fs';

const C0 = 299792458;
const Z0 = 50;
const Cs = 40e-15; // series gap capacitance
const Cp = 12e-15; // shunt fringing capacitance, each side
const L1 = 1.5e-3; // port 1 reference line length (m)
const L2 = 3.0e-3; // port 2 reference line length (m)
const EEFF = 5.4; // CPW on alumina, roughly
const F0 = 1e9;
const F1 = 40e9;
const N = 201;

const add = (a, b) => [a[0] + b[0], a[1] + b[1]];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const mul = (a, b) => [a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0]];
const div = (a, b) => {
  const d = b[0] * b[0] + b[1] * b[1];
  return [(a[0] * b[0] + a[1] * b[1]) / d, (a[1] * b[0] - a[0] * b[1]) / d];
};
const cexp = (a) => [Math.exp(a[0]) * Math.cos(a[1]), Math.exp(a[0]) * Math.sin(a[1])];
const scale = (a, k) => [a[0] * k, a[1] * k];
const ONE = [1, 0];

const lines = [
  '! PLACEHOLDER DATA - synthetic pi model of a CPW series gap, not EM simulated.',
  `! Cs=${Cs * 1e15} fF, Cp=${Cp * 1e15} fF, L1=${L1 * 1e3} mm, L2=${L2 * 1e3} mm, eeff=${EEFF}`,
  '! Generated by scripts/gen-cpw-placeholder.mjs',
  '# GHZ S RI R 50',
];

for (let k = 0; k < N; k++) {
  const f = F0 + ((F1 - F0) * k) / (N - 1);
  const w = 2 * Math.PI * f;

  // Normalized Y-parameters of the symmetric pi network.
  const y11 = [0, w * (Cs + Cp) * Z0];
  const y12 = [0, -w * Cs * Z0];

  const onePlus = add(ONE, y11);
  const den = sub(mul(onePlus, onePlus), mul(y12, y12));
  const s11 = div(add(mul(sub(ONE, y11), onePlus), mul(y12, y12)), den);
  const s21 = div(scale(y12, -2), den);

  // Lossy CPW reference lines: gamma = alpha + j beta.
  const alpha = 4 * Math.sqrt(f / 1e9); // Np/m
  const beta = (w * Math.sqrt(EEFF)) / C0;
  const g = [alpha, beta];
  const S11 = mul(s11, cexp(scale(g, -2 * L1)));
  const S22 = mul(s11, cexp(scale(g, -2 * L2)));
  const S21 = mul(s21, cexp(scale(g, -(L1 + L2))));

  const fmt = (c) => `${c[0].toFixed(6)} ${c[1].toFixed(6)}`;
  lines.push(`${(f / 1e9).toFixed(4)} ${fmt(S11)} ${fmt(S21)} ${fmt(S21)} ${fmt(S22)}`);
}

mkdirSync('public/smith', { recursive: true });
writeFileSync('public/smith/cpw-gap.s2p', lines.join('\n') + '\n');
console.log(`wrote public/smith/cpw-gap.s2p (${N} points)`);
